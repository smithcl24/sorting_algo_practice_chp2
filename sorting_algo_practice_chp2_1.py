def selection_sort_smallest(list):

  for i in range(len(list)):

    smallest_index = i

    for j in range(i + 1, len(list)):
      if list[j] < list[smallest_index]:
        smallest_index = j

    temp = list[i]
    list[i] = list[smallest_index]
    list[smallest_index] = temp

  return list

