List_A = [3, 4, 7, 1, 3]

def insertion_sort_asc(list):

    for i in range(1, len(list)):
        key = list[i]
        j = i - 1
        while j >= 0 and list[j] > key:
            list[j + 1] = list[j]
            j = j - 1

        list[j + 1] = key

    return list

insertion_sort_asc(List_A)

